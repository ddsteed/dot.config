# -----------------------------------------------------------------------------
# 功能说明
# -----------------------------------------------------------------------------
# 此脚本是 smart_open.sh 的批量处理版本
# 可以同时处理多个文件
#
# 与 smart_open.sh 的区别:
#   - smart_open.sh: 单文件处理，返回退出码 1 让 yazi 继续尝试其他规则
#   - open_smart.sh: 批量处理，所有未知类型也用 open 打开
#
# 适用场景:
#   - 需要批量打开多个选中文件时
#   - 需要统一处理逻辑时
# -----------------------------------------------------------------------------

# 处理所有传入的文件参数
for file in "$@"; do
    # 提取文件扩展名并转为小写
    ext="${file##*.}"
    ext=$(echo "$ext" | tr '[:upper:]' '[:lower:]')

    # 根据扩展名处理
    case "$ext" in
        # iWork 套件文件 - 使用系统默认打开
        pages|numbers|key)
            open "$file"
            ;;
        *)
            # 其他文件也使用系统默认打开
            # 注意：这与 smart_open.sh 的行为不同
            open "$file"
            ;;
    esac
done
