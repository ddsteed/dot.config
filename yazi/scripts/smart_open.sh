# -----------------------------------------------------------------------------
# 功能说明
# -----------------------------------------------------------------------------
# 此脚本用于 yazi 的文件打开规则（[open] prepend_rules）
#
# 工作原理:
#   1. 接收文件路径作为参数
#   2. 根据文件扩展名判断文件类型
#   3. iWork 文件使用 macOS 系统默认程序打开
#   4. 其他文件返回退出码 1，让 yazi 使用默认处理
#
# 使用方式:
#   在 yazi.toml 中配置:
#   [open]
#   prepend_rules = [
#     { name = "*.pages", use = ["run", "$HOME/.config/yazi/scripts/smart_open.sh"] },
#     ...
#   ]
# -----------------------------------------------------------------------------

# 获取输入文件
FILE="$1"

# 提取文件扩展名并转为小写
EXT="${FILE##*.}"
EXT=$(echo "$EXT" | tr '[:upper:]' '[:lower:]')

# 根据扩展名处理
case "$EXT" in
    # iWork 套件文件 - 使用系统默认打开
    pages|numbers|key)
        open "$FILE"
        ;;
    *)
        # 其他文件 - 返回非零状态让 yazi 使用默认行为
        exit 1
        ;;
esac
